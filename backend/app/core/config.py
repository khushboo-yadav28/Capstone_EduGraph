
from dotenv import load_dotenv
import os
from pathlib import Path

load_dotenv()

DATABASE_URL = os.getenv("DATABASE_URL")

GEMINI_API_KEY = os.getenv("GEMINI_API_KEY")
GEMINI_PRIMARY_MODEL = os.getenv(
    "GEMINI_PRIMARY_MODEL",
    "gemini-2.5-flash",
)
GEMINI_FALLBACK_MODEL = os.getenv(
    "GEMINI_FALLBACK_MODEL",
    "gemini-flash-latest",
)

GEMINI_INGESTION_TEMPERATURE = float(
    os.getenv("GEMINI_INGESTION_TEMPERATURE", "0.2")
)
GEMINI_INGESTION_MAX_TOKENS = int(
    os.getenv("GEMINI_INGESTION_MAX_TOKENS", "16384")
)

GEMINI_CHAT_TEMPERATURE = float(
    os.getenv("GEMINI_CHAT_TEMPERATURE", "0.2")
)
GEMINI_CHAT_MAX_TOKENS = int(
    os.getenv("GEMINI_CHAT_MAX_TOKENS", "1500")
)

RESPONSE_MIME_TYPE = os.getenv("RESPONSE_MIME_TYPE")

SECRET_KEY = os.getenv("SECRET_KEY")
ALGORITHM = os.getenv("ALGORITHM")
ACCESS_TOKEN_EXPIRE_MINUTES = int(
    os.getenv("ACCESS_TOKEN_EXPIRE_MINUTES") or 30
)

# Storage and upload directory configuration
BASE_DIR = Path(
    os.path.dirname(
        os.path.dirname(
            os.path.dirname(os.path.abspath(__file__))
        )
    )
)

UPLOAD_DIR = Path(
    os.getenv("UPLOAD_DIR", str(BASE_DIR / "uploads"))
)


class Settings:
    BASE_DIR = BASE_DIR
    UPLOAD_DIR = UPLOAD_DIR
    DATABASE_URL = DATABASE_URL
    GEMINI_API_KEY = GEMINI_API_KEY
    GEMINI_PRIMARY_MODEL = GEMINI_PRIMARY_MODEL
    GEMINI_FALLBACK_MODEL = GEMINI_FALLBACK_MODEL

    GEMINI_INGESTION_TEMPERATURE = GEMINI_INGESTION_TEMPERATURE
    GEMINI_INGESTION_MAX_TOKENS = GEMINI_INGESTION_MAX_TOKENS

    GEMINI_CHAT_TEMPERATURE = GEMINI_CHAT_TEMPERATURE
    GEMINI_CHAT_MAX_TOKENS = GEMINI_CHAT_MAX_TOKENS

    RESPONSE_MIME_TYPE = RESPONSE_MIME_TYPE
    SECRET_KEY = SECRET_KEY
    ALGORITHM = ALGORITHM
    ACCESS_TOKEN_EXPIRE_MINUTES = ACCESS_TOKEN_EXPIRE_MINUTES


settings = Settings()
